"""Per-frame value targets for the LIBERO Stage 2 rollouts (docs/libero_plan.md), with vl.targets unchanged.

Usage:
    .venv/bin/python -m vl.libero_targets --dataset /iris/u/ankile/karenvo/libero/lerobot/libero_moka_stage2

Reads the episode table written by scripts/libero_to_lerobot.py, turns it into a manifest in vl.targets'
format (one row per LeRobot episode: T = policy_steps - 1, the last frame with an action; outcome success /
timeout), and builds targets with the `targets:` block of configs/libero_moka.yaml (horizon = libero_10's
max_steps = 520, failure penalty 520, so successes land in (-0.5, 0] and failures in [-1, -0.5]).
Sim labels are exact: there is no "unknown" outcome. Writes <dataset>/frame_targets.parquet and
<dataset>/targets_summary.md.
"""

import argparse
from pathlib import Path

import pandas as pd

from vl.config import load_config
from vl.targets import build_targets, summarize

FPS = 10  # LeRobot fps of the Stage 2 data (as openpi's LIBERO dataset); only used for time_to_go_s


def manifest_from_episodes(ep: pd.DataFrame) -> pd.DataFrame:
    """vl.targets manifest columns from the converter's episodes.csv."""
    if (ep.success.astype(int) + ep.timeout.astype(int) != 1).any():
        raise ValueError("every converted episode must be either a success or a timeout")
    return pd.DataFrame({
        "episode_uid": "libero_moka/" + ep.episode_index.astype(str),
        "repo": "libero_moka",
        "episode_index": ep.episode_index.astype(int),
        "split": ep.split,
        "exclude_reason": "",
        "T": ep.policy_steps.astype(int) - 1,
        "fps": float(FPS),
        "outcome": ep.success.astype(int).map({1: "success", 0: "timeout"}),
        "init_state": ep.init_state.astype(int),
    })


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dataset", required=True, help="LeRobot dataset dir with episodes.csv")
    ap.add_argument("--config", default="configs/libero_moka.yaml")
    args = ap.parse_args()
    cfg = load_config(args.config)
    ds = Path(args.dataset)
    man = manifest_from_episodes(pd.read_csv(ds / "episodes.csv"))
    ft = build_targets(man, cfg["targets"])
    ft = ft.merge(man[["episode_uid", "init_state"]], on="episode_uid")
    ft.to_parquet(ds / "frame_targets.parquet")
    s = summarize(ft)
    (ds / "targets_summary.md").write_text(
        f"# LIBERO moka targets\n\nGenerated by `python -m vl.libero_targets` from `{ds / 'episodes.csv'}` with "
        f"`{args.config}` (targets block).\n\n" + s.to_markdown(index=False, floatfmt=".4f") + "\n")
    print(f"wrote {ds / 'frame_targets.parquet'}: {len(ft)} frames from {ft.episode_uid.nunique()} episodes")
    print(s.to_string(index=False))
    print("out-of-support frames:", int((~ft.in_support).sum()))


if __name__ == "__main__":
    main()
