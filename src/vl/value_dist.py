"""Full predicted value distributions (all 201 bins) of a run's best.pt on the validation split.

Usage (on a GPU node; see scripts/value_dist.sbatch):
    .venv/bin/python -u -m vl.value_dist --run lowlr_8k
        -> data/runs/<run>/val_probs.npz   (probs float16 (n_val, 201), same row order as
                                            val_predictions.parquet, plus V for a consistency check)
    .venv/bin/python -u -m vl.value_dist --run lowlr_8k --plotted
        -> data/runs/<run>/val_probs_plotted.npz  (only the episodes vl.value_plots draws; ~1 min)
    .venv/bin/python -m vl.value_dist --run lowlr_8k --plots      (CPU, needs val_probs.npz)
        -> reports/figures/stage4/<run>/dist_*.png, reports/value_dist_<run>.md

val_predictions.parquet keeps only the mean V = sum_b p_b v_b. This keeps the whole
distribution, so we can ask what V's mean is averaging over (e.g. a success mode and a failure
mode at once). Eval mode, same preprocessing and AMP as the training-time validation pass.
"""

import argparse
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import DataLoader

from vl.config import load_config
from vl.dataset import FrameDataset, load_split
from vl.model import build_model, model_inputs, run_data_config
from vl.train import amp_dtype


def plots(run: Path, name: str, tcfg: dict):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import pandas as pd

    from vl.analysis import md
    from vl.metrics import auc

    z = np.load(run / "val_probs.npz")
    pred = pd.read_parquet(run / "val_predictions.parquet")
    assert (pred.frame_index.to_numpy() == z["frame_index"]).all()
    assert np.abs(pred.V.to_numpy() - z["V"]).max() < 0.02, "probs do not match val_predictions (AMP noise only)"
    P = z["probs"].astype(np.float32)
    v = np.linspace(tcfg["v_min"], tcfg["v_max"], tcfg["n_bins"])
    succ_bins = v > -0.5                     # success targets are in (-0.5, 0], failures in [-1, -0.5]
    man = pd.read_parquet("data/manifest/episodes.parquet").set_index("episode_uid")
    pred = pred.join(man[["source_type", "has_human_frames"]], on="episode_uid")
    pred["p_succ"] = P[:, succ_bins].sum(1)
    # Mean of each half: what V would be if the model were sure of the outcome.
    pred["V_if_succ"] = (P[:, succ_bins] * v[succ_bins]).sum(1) / np.maximum(pred.p_succ, 1e-6)
    pred["V_if_fail"] = (P[:, ~succ_bins] * v[~succ_bins]).sum(1) / np.maximum(1 - pred.p_succ, 1e-6)
    pred["to_T_s"] = (pred["T"] - pred.frame_index) / 15
    pred["auto"] = (pred.source_type == "eval") & ~pred.has_human_frames
    out_dir = Path("reports/figures/stage4") / name
    out_dir.mkdir(parents=True, exist_ok=True)
    lines = [f"# Full value distributions: `{name}` (generated by `vl.value_dist --plots`)\n",
             "Validation, best checkpoint. p_succ = probability mass on bins above -0.5 (the success range).\n"]

    # 1. Per-episode heatmaps: p(bin) over time, with V and the target on top.
    picks = {"01 clean success r04/39": ("real-marker-d2-r04-eval", 39), "10 worst success r01/103": ("real-marker-d2-r01-eval", 103),
             "02 failure r04/20": ("real-marker-d2-r04-eval", 20), "09 capped timeout r04/101": ("real-marker-d2-r04-eval", 101)}
    fig, axes = plt.subplots(len(picks), 1, figsize=(10, 3.1 * len(picks)))
    for ax, (title, (repo, ep)) in zip(axes, picks.items()):
        ix = np.flatnonzero((pred.repo == repo).to_numpy() & (pred.episode_index == ep).to_numpy())
        e = pred.iloc[ix]
        t = e.frame_index.to_numpy() / 15
        ax.imshow(np.sqrt(P[ix].T), origin="lower", aspect="auto", cmap="Greys",
                  extent=[t[0], t[-1] + 1 / 15, v[0] - 0.0025, v[-1] + 0.0025])
        ax.plot(t, e.value, color="black", lw=1.5, label="target v")
        ax.plot(t, e.V, color="tab:orange", lw=1, label="V = mean of the distribution")
        ax.plot(t, e.p_succ - 1, color="tab:blue", lw=1, alpha=0.8, label="p_succ - 1 (mass above -0.5)")
        ax.axhline(-0.5, color="tab:red", lw=0.6, ls="--")
        ax.set_ylim(-1, 0.01); ax.set_ylabel("value"); ax.set_title(f"{title} ({e.outcome.iloc[0]}, T = {t[-1]:.1f} s)", fontsize=9)
    axes[0].legend(fontsize=7, loc="lower left"); axes[-1].set_xlabel("time (s)")
    fig.suptitle("Predicted distribution over the 201 bins at every frame (darker = more probability, sqrt scale)", fontsize=10)
    fig.tight_layout(); fig.savefig(out_dir / "dist_heatmaps.png", dpi=110); plt.close(fig)

    # 2. Distribution of predicted V vs targets, by outcome (all val frames).
    fig, axes = plt.subplots(1, 3, figsize=(12, 3.2), sharey=False)
    h = np.linspace(-1, 0, 41)
    for ax, o in zip(axes, ["success", "failure", "timeout"]):
        s_ = pred[pred.outcome == o]
        ax.hist(s_.value, h, alpha=0.5, label="target v", color="black")
        ax.hist(s_.V, h, alpha=0.6, label="predicted V", color="tab:orange")
        ax.axvline(-0.5, color="tab:red", lw=0.6, ls="--")
        ax.set_title(f"{o} ({s_.episode_uid.nunique()} episodes, {len(s_):,} frames)", fontsize=9); ax.set_xlabel("value")
    axes[0].legend(fontsize=8); axes[0].set_ylabel("frames")
    fig.tight_layout(); fig.savefig(out_dir / "dist_hist_by_outcome.png", dpi=110); plt.close(fig)

    # 3. Average predicted distribution at fixed times before the end (autonomous episodes).
    a = pred[pred.auto]
    fig, axes = plt.subplots(1, 2, figsize=(12, 3.4), sharey=True)
    rows = []
    for ax, (o, sel) in zip(axes, [("success", a.outcome == "success"), ("failure + timeout", a.outcome != "success")]):
        for lo, hi in [(0, 1), (3, 5), (10, 20), (20, 60)]:
            w = sel & (a.to_T_s >= lo) & (a.to_T_s < hi)
            ax.plot(v, P[a.index[w]].mean(0), label=f"{lo}-{hi} s before T (target mean {a.value[w].mean():.2f})")
        ax.axvline(-0.5, color="tab:red", lw=0.6, ls="--"); ax.set_title(f"autonomous {o}: mean predicted distribution", fontsize=9)
        ax.set_xlabel("value bin"); ax.legend(fontsize=7)
    axes[0].set_ylabel("mean probability")
    fig.tight_layout(); fig.savefig(out_dir / "dist_mean_by_time.png", dpi=110); plt.close(fig)

    # Tables: by time to the end, autonomous episodes.
    a = a.assign(ttg=pd.cut(a.to_T_s, [-0.01, 1, 3, 5, 10, 20, 60]))
    for k, g in a.groupby("ttg", observed=True):
        s_, f_ = g[g.outcome == "success"], g[g.outcome != "success"]
        ep = g.groupby("episode_uid").agg(p=("p_succ", "mean"), s=("outcome", lambda x: x.iloc[0] == "success"))
        rows.append({"time to end (s)": str(k), "p_succ | success": s_.p_succ.mean(), "p_succ | not": f_.p_succ.mean(),
                     "AUC(p_succ)": auc(ep.s.to_numpy().astype(int), ep.p.to_numpy()),
                     "V if succ (mean of upper half) | success": s_.V_if_succ.mean(), "target | success": s_.value.mean(),
                     "V if fail (mean of lower half) | not": f_.V_if_fail.mean(), "target | not": f_.value.mean()})
    lines += ["## Autonomous episodes by time to the end\n", md(pd.DataFrame(rows).set_index("time to end (s)")) + "\n"]
    # How much of V's movement is the outcome belief? V = p*Vs + (1-p)*Vf; frame-to-frame changes.
    e = pred.sort_values(["episode_uid", "frame_index"])
    d = e.groupby("episode_uid")[["V", "p_succ", "V_if_succ", "V_if_fail"]].diff().dropna()
    gap = (e.V_if_succ - e.V_if_fail).loc[d.index]
    from_p = d.p_succ * gap
    r2 = 1 - ((d.V - from_p) ** 2).sum() / ((d.V - d.V.mean()) ** 2).sum()
    lines += [f"Frame-to-frame changes of V explained by the change of p_succ alone (ΔV ≈ Δp_succ × (V_if_succ - V_if_fail)): "
              f"R² = {r2:.3f}. Mean gap V_if_succ - V_if_fail = {gap.mean():.3f}.\n",
              f"Fraction of val frames with V < -0.6: {(pred.V < -0.6).mean():.4f} (targets: {(pred.value < -0.6).mean():.3f}). "
              f"Min V {pred.V.min():.3f}. Mean mass below -0.6: {P[:, v < -0.6].sum(1).mean():.3f}.\n"]
    out = Path("reports") / f"value_dist_{name}.md"
    out.write_text("\n".join(lines))
    print("->", out, out_dir)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/train.yaml")
    ap.add_argument("--run", required=True)
    ap.add_argument("--workers", type=int, default=16)
    ap.add_argument("--plotted", action="store_true", help="only the episodes vl.value_plots draws")
    ap.add_argument("--plots", action="store_true", help="CPU: figures and tables from an existing val_probs.npz")
    args = ap.parse_args()
    cfg = load_config(args.config)
    dcfg, tcfg = load_config(cfg["data_config"]), load_config(cfg["target_config"])
    run = Path(cfg["paths"]["runs"]) / args.run
    if args.plots:
        return plots(run, args.run, tcfg)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    dtype = amp_dtype(cfg["amp"])
    val = load_split(dcfg, "val")
    out = run / "val_probs.npz"
    if args.plotted:
        import pandas as pd

        from vl.value_plots import choose_episodes
        man = pd.read_parquet(load_config(dcfg["dataset_config"])["paths"]["manifest"])
        uids = [u for _, u in choose_episodes(pd.read_parquet(run / "val_predictions.parquet"), man)]
        val = val[val.episode_uid.isin(uids)].reset_index(drop=True)
        out = run / "val_probs_plotted.npz"
        print(f"{len(uids)} plotted episodes, {len(val):,} frames", flush=True)
    dcfg = run_data_config(dcfg, run)
    model = build_model(dcfg, tcfg).to(device).eval()
    ck = torch.load(run / "best.pt", map_location=device)
    model.load_state_dict(ck["model"])
    dl = DataLoader(FrameDataset(val, dcfg), batch_size=128, shuffle=False, num_workers=args.workers,
                    pin_memory=True, prefetch_factor=4)
    probs = np.empty((len(val), tcfg["n_bins"]), np.float16)
    V = np.empty(len(val), np.float32)
    with torch.no_grad():
        for i, b in enumerate(dl):
            x, p = model_inputs(b, device)
            with torch.autocast("cuda", dtype=dtype, enabled=dtype is not None):
                logits = model(x, p)
            rows = b["row"].numpy()
            probs[rows] = torch.softmax(logits.float(), dim=1).cpu().numpy()
            V[rows] = model.expected_value(logits).cpu().numpy()
            if i % 100 == 0:
                print(f"  batch {i}/{len(dl)}", flush=True)
    np.savez(out, probs=probs, V=V, frame_index=val.frame_index.to_numpy(),
             episode_uid=val.episode_uid.to_numpy().astype(str))
    print(f"-> {out}  (best step {ck['step']})", flush=True)


if __name__ == "__main__":
    main()
